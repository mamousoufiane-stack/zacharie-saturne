import {chromium} from '@playwright/test';
import fs from 'node:fs';
fs.mkdirSync('test-results',{recursive:true});
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const gameUrl=process.env.GAME_URL||'http://localhost:5173';
const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('response',response=>{if(response.status()>=400)console.log('HTTP_ERROR',response.status(),response.url());});
page.on('console',message=>{if(message.type()==='error')errors.push(message.text()+JSON.stringify(message.location()));});
await page.goto(gameUrl);
await page.waitForFunction(()=>window.__saturn?.world.hero.status==='ready'&&!document.querySelector('#play').disabled,{timeout:60000});
await page.screenshot({path:'test-results/menu.png'});
console.log('MODEL',await page.evaluate(()=>({status:__saturn.world.hero.status,animation:__saturn.world.hero.animation,meshes:__saturn.world.renderer.info.render.calls})));
await page.locator('#play').click();
await page.waitForFunction(()=>__saturn.mode==='playing');
await page.waitForTimeout(500);
await page.screenshot({path:'test-results/idle.png'});
await page.keyboard.press('Space');
await page.waitForFunction(()=>__saturn.state.airborne);
await page.waitForTimeout(400);
await page.screenshot({path:'test-results/jump.png'});
await page.waitForFunction(()=>__saturn.state.island===1&&!__saturn.state.airborne);
await page.waitForTimeout(400);
await page.screenshot({path:'test-results/landed.png'});
console.log('LANDED',await page.evaluate(()=>({island:__saturn.state.island,distance:__saturn.state.distance,animation:__saturn.world.hero.animation})));
await page.keyboard.press('Escape');await page.waitForFunction(()=>__saturn.mode==='paused');
const position=await page.evaluate(()=>__saturn.state.distance);await page.waitForTimeout(300);
if(await page.evaluate(()=>__saturn.state.distance)!==position)throw Error('Pause moves the player');
console.log('ERRORS',JSON.stringify(errors));
await page.keyboard.press('Escape');
await page.waitForFunction(()=>__saturn.mode==='playing');
await page.evaluate(()=>__saturn.state.seekToIsland(35));
await page.keyboard.press('Space');await page.waitForFunction(()=>__saturn.mode==='finished');
await page.waitForTimeout(400);await page.screenshot({path:'test-results/victory.png'});
console.log('VICTORY',await page.evaluate(()=>({island:__saturn.state.island,animation:__saturn.world.hero.animation})));
const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1});
mobile.on('pageerror',error=>errors.push(error.message));
await mobile.goto(gameUrl);await mobile.waitForFunction(()=>window.__saturn?.world.hero.status==='ready'&&!document.querySelector('#play').disabled);
await mobile.locator('#play').tap();await mobile.waitForFunction(()=>__saturn.mode==='playing');
await mobile.locator('#jump').tap();await mobile.waitForFunction(()=>__saturn.state.island===1&&!__saturn.state.airborne);
await mobile.screenshot({path:'test-results/mobile.png'});
console.log('MOBILE',await mobile.evaluate(()=>({island:__saturn.state.island,overflow:document.documentElement.scrollWidth>innerWidth})));
console.log('FINAL_ERRORS',JSON.stringify(errors));
await browser.close();if(errors.length)process.exitCode=1;

